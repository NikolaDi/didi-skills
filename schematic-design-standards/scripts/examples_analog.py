"""模拟与参考域的通用布局校验图。"""
from pathlib import Path
from svg_circuit import Drawing


def build(out):
    out=Path(out);out.mkdir(parents=True,exist_ok=True)
    paths=[]

    d=Drawing(5,'分压、滤波与 ADC 保护','竖直分压形成清楚的取样点；串联元件前后保留独立节点。')
    d.section(80,158,'输入取样');d.section(470,158,'局部滤波与钳位')
    d.port((100,230),'VIN_SENSE');d.wire((100,230),(260,230))
    d.resistor('R1','分压上臂',(260,230),(260,330),'VIN_SENSE','SENSE_RAW')
    d.resistor('R2','分压下臂',(260,330),(260,470),'SENSE_RAW','AGND')
    d.ground((260,470),'AGND');d.dot(260,330)
    d.wire((260,330),(400,330))
    d.resistor('Rf','串联限流',(400,330),(520,330),'SENSE_RAW','ADC_IN')
    d.wire((520,330),(970,330));d.port((970,330),'ADC_IN',align='end')
    d.cap('Cf','低通滤波',(640,330),(640,470),'ADC_IN','AGND');d.ground((640,470),'AGND');d.dot(640,330)
    d.wire((790,330),(790,270));d.diode('D1',(790,270),(790,190),'ADC_IN','VCLAMP')
    d.wire((790,190),(790,170));d.power((790,170),'VCLAMP')
    d.wire((790,330),(790,390));d.diode('D2',(790,470),(790,390),'AGND','ADC_IN')
    d.ground((790,470),'AGND');d.dot(790,330)
    d.checks('检查：分压、Rf 前后、ADC 节点保持区分；Cf 与钳位均接到实际被保护节点。','布局不决定保护能力；钳位电源轨与器件参数需要单独设计。')
    paths.append(d.save(out/'05-adc-input.svg'))

    d=Drawing(6,'运放与负反馈','主输入、输出横向展开，反馈从上方返回，电源和参考端就地明确。')
    p=d.opamp('U1',560,350,{'-':'FB','+':'VIN','OUT':'VOUT','V+':'+5VA','V-':'AGND'})
    d.port((90,380),'VIN');d.wire((90,380),p['+'])
    d.wire(p['OUT'],(950,350));d.port((950,350),'VOUT',align='end');d.dot(800,350)
    d.wire((800,350),(800,160),(650,160))
    d.resistor('Rf','反馈',(430,160),(650,160),'FB','VOUT')
    d.wire((430,160),(360,160),(360,320),p['-']);d.dot(360,320)
    d.resistor('Rg','增益设定',(150,320),(300,320),'AGND','FB');d.wire((300,320),(360,320));d.ground((150,320),'AGND')
    d.wire(p['V+'],(560,250));d.power((560,250),'+5VA')
    d.wire(p['V-'],(560,480));d.ground((560,480),'AGND')
    d.power((930,180),'+5VA');d.wire((930,180),(930,210))
    d.cap('C1','去耦',(930,210),(930,270),'+5VA','AGND');d.ground((930,270),'AGND')
    d.checks('检查：Rf 返回反相端；输入不穿过反馈元件；供电、参考地和去耦归属明确。','同相放大拓扑仅用于图面校验；增益、带宽和稳定性另行验证。')
    paths.append(d.save(out/'06-opamp-feedback.svg'))

    d=Drawing(7,'比较器与迟滞反馈','保持真实的正反馈路径，不将比较器强行套入运放负反馈画法。')
    p=d.opamp('U1',560,350,{'-':'VIN','+':'HYS','OUT':'CMP_OUT','V+':'+3V3','V-':'GND'},comparator=True)
    d.port((100,320),'VIN');d.wire((100,320),p['-'])
    d.port((100,430),'VREF');d.wire((100,430),(220,430))
    d.resistor('Rref','阈值网络',(220,430),(350,430),'VREF','HYS')
    d.wire((350,430),(440,430),(440,380),p['+']);d.dot(440,430)
    d.wire(p['OUT'],(960,350));d.port((960,350),'CMP_OUT',align='end');d.dot(820,350)
    d.wire((820,350),(820,510),(760,510))
    d.resistor('Rh','正反馈',(540,510),(760,510),'HYS','CMP_OUT')
    d.wire((540,510),(440,510),(440,430))
    d.wire(p['V+'],(560,220));d.power((560,220),'+3V3')
    d.wire(p['V-'],(560,450));d.ground((560,450))
    d.text(805,285,'推挽输出示意',16)
    d.power((950,180),'+3V3');d.wire((950,180),(950,210))
    d.cap('C1','去耦',(950,210),(950,250),'+3V3','GND');d.ground((950,250))
    d.checks('检查：Rh 从输出回到“+”端；输入进入“−”端；阈值支路与反馈汇合点清楚。','输出类型按实际器件定义；开漏输出需另行配置所需上拉。')
    paths.append(d.save(out/'07-comparator-hysteresis.svg'))

    d=Drawing(12,'参考源、分压与缓冲','参考电压和供电各有身份，分压点送入缓冲器，反馈在局部闭合。')
    p=d.ic('U1','参考源',190,220,160,140,[('VIN','L',50,'+5VA'),('REF','R',50,'VREF'),('GND','B',80,'AGND')])
    d.power((100,220),'+5VA');d.wire((100,220),(100,270),p['VIN']);d.dot(100,270)
    d.cap('C1','去耦',(100,270),(100,420),'+5VA','AGND');d.ground((100,420),'AGND')
    d.wire(p['GND'],(270,420));d.ground((270,420),'AGND')
    d.wire(p['REF'],(470,270));d.port((385,270),'VREF')
    d.resistor('R1','分压上臂',(470,270),(470,360),'VREF','VBIAS')
    d.resistor('R2','分压下臂',(470,360),(470,480),'VBIAS','AGND');d.ground((470,480),'AGND');d.dot(470,360)
    q=d.opamp('U2',690,330,{'-':'VBIAS_BUF','+':'VBIAS','OUT':'VBIAS_BUF','V+':'+5VA','V-':'AGND'})
    d.wire((470,360),q['+']);d.port((560,360),'VBIAS')
    d.wire(q['OUT'],(1000,330));d.port((1000,330),'VBIAS_BUF',align='end');d.dot(860,330)
    d.wire((860,330),(860,160),(570,160),(570,300),q['-'])
    d.wire(q['V+'],(690,210));d.power((690,210),'+5VA')
    d.wire(q['V-'],(690,470));d.ground((690,470),'AGND')
    d.power((970,180),'+5VA');d.wire((970,180),(970,210))
    d.cap('C2','去耦',(970,210),(970,250),'+5VA','AGND');d.ground((970,250),'AGND')
    d.checks('检查：参考源 → 分压 → 缓冲的阅读顺序连续；输出返回反相端形成跟随器。','VREF、VBIAS 与 VBIAS_BUF 为不同节点，不因名称相似而合并。')
    paths.append(d.save(out/'12-reference-buffer.svg'))

    d=Drawing(14,'电源域、滤波与参考地','串联滤波前后分网，同一电源域的并联支路有序对齐。')
    d.port((90,210),'+3V3_D');d.wire((90,210),(260,210))
    d.passive('FB','FB1','滤波磁珠',(260,210),(420,210),'+3V3_D','+3V3_A')
    d.wire((420,210),(970,210));d.port((970,210),'+3V3_A',align='end')
    d.cap('C1','输入旁路',(160,210),(160,320),'+3V3_D','DGND');d.ground((160,320),'DGND');d.dot(160,210)
    d.cap('C2','高频旁路',(560,210),(560,320),'+3V3_A','AGND');d.ground((560,320),'AGND');d.dot(560,210)
    d.cap('C3','储能',(800,210),(800,320),'+3V3_A','AGND');d.ground((800,320),'AGND');d.dot(800,210)
    d.section(250,426,'仅在设计明确规定时连接不同参考域')
    d.resistor('R0','0 Ω / 由设计决定',(420,480),(650,480),'AGND','DGND')
    d.ground((420,480),'AGND');d.ground((650,480),'DGND')
    d.checks('检查：滤波前后电源身份不同；旁路分组清楚；参考域连接位置明确。','不为美观拆分地网；原理图上的分组不能替代 PCB 回流与布局设计。')
    paths.append(d.save(out/'14-power-domains.svg'))
    return paths


if __name__=='__main__':
    build(Path(__file__).resolve().parents[1]/'assets/examples')
